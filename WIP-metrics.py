def get_metrics(cm, class_names):
    print('\n\n\n')
    cm = numpy.array(cm)
    true_pos = np.diag(cm)
    precision = np.sum(true_pos / np.sum(cm, axis=0))/len(class_names)
    recall = np.sum(true_pos / np.sum(cm, axis=1))/len(class_names)

    f1score = ((2 * precision * recall)/(precision + recall))

    print('Precision: ' + str(precision*100))
    print('Recall: ' + str(recall*100))
    print('F1-Score: ' + str(f1score*100))
    print('')

    tp = np.diag(cm)
    prec = list(map(truediv, tp, np.sum(cm, axis=0)))
    rec = list(map(truediv, tp, np.sum(cm, axis=1)))

    for i in range(len(class_names)):
        f1score_tmp = ((2 * prec[i] * rec[i]) / (prec[i] + rec[i]))
        print(class_names[i].title() + ' &  & ' + str((prec[i]*100).round(2)) + ' & ' + str((rec[i]*100).round(2)) + ' & ' + str((f1score_tmp*100).round(2)) + ' \\\\')


